"""Offline exports from the Design: cable map CSV, generated BOM, IP plan, rack power,
the draw.io drawings (drawio.py) and the 3D scene (scene.py).

These are derived artefacts — regenerate with `bin/dgxnb export`; never hand-edit.
"""
from __future__ import annotations

import csv
from collections import Counter, defaultdict
from pathlib import Path

from .model import Design

DGX_PREFIX = "nvidia-dgx-"


def _type(o) -> str:
    return o.data["device_type"].key[0]


def _role(o) -> str:
    return o.data["role"].key[0]


def pod_specs(spec: dict) -> dict[str, dict]:
    """{pod name: pod spec}; a single-pod design is its own (only) pod."""
    if "pods" in spec:
        return {k: v["spec"] for k, v in spec["pods"].items()}
    return {"": spec}


def node_roles(spec: dict) -> dict[str, int]:
    """{compute-node device role: GPUs per node} across every pod of the design."""
    return {p.get("validate", {}).get("compute_role", "dgx-compute"): p["compute"]["gpus_per_node"]
            for p in pod_specs(spec).values()}


def rack_budget(spec: dict, rack: str) -> float:
    """Peak-kW budget for a rack: management and storage racks vs compute (DGX / NVL72).
    In a mixed design the budget comes from the pod the rack belongs to."""
    if "pods" in spec:
        from .topology_mixed import pod_of_rack
        spec = spec["pods"][pod_of_rack(spec, rack)]["spec"]
    r = spec["racks"]
    if "mgmt" in rack or rack in r.get("storage_racks", []):
        return r["budget_kw_mgmt_rack"]
    return r.get("budget_kw_dgx_rack", r.get("budget_kw_compute_rack"))


def design_summary(spec: dict) -> str:
    """One line for report headers, e.g. '2 SU, DGX H200' or '1 SU DGX H200 + 1 SU DGX GB300'."""
    parts = [f"{p['compute']['sus']} SU DGX {p['compute']['gpu_gen'].upper()}"
             for p in pod_specs(spec).values()]
    return " + ".join(parts)


def rack_power(types: dict, design: Design) -> dict[str, float]:
    """Peak kW per rack = sum of allocated_draw (set to peak / PSU count) of its devices."""
    kw: dict[str, float] = defaultdict(float)
    for o in design.all("dcim.devices"):
        rack = o.data.get("rack")
        if not rack:
            continue
        draw = sum(p.get("allocated_draw", 0) for p in types[_type(o)].get("power-ports", []))
        kw[rack.key[0]] += draw / 1000
    return dict(kw)


def counts(spec: dict, types: dict, design: Design) -> dict:
    """Headline numbers used by the BOM, the tests and bin/validate."""
    devs = design.all("dcim.devices")
    gpn = node_roles(spec)
    dgx = [o for o in devs if _role(o) in gpn]
    cables = design.all("dcim.cables")
    by_fabric = Counter(c.data["custom_fields"]["dgx_fabric"] for c in cables)
    return {
        "dgx": len(dgx),
        "gpus": sum(gpn[_role(o)] for o in dgx),
        "roles": Counter(_role(o) for o in devs),
        "types": Counter(_type(o) for o in devs),
        "racks": design.count("dcim.racks"),
        "feeds": design.count("dcim.power_feeds"),
        "cables": len(cables),
        "cables_by_fabric": by_fabric,
        "cables_by_type": Counter((c.data["custom_fields"]["dgx_fabric"], c.data["type"])
                                  for c in cables),
        "ips": design.count("ipam.ip_addresses"),
        "rack_kw": rack_power(types, design),
    }


def bom_markdown(spec: dict, types: dict, design: Design) -> str:
    c = counts(spec, types, design)
    L = ["# Generated BOM", "",
         f"Generated by `bin/dgxnb export` from `spec/` — {design_summary(spec)}. "
         "Do not edit; sources are in the RA notes.", "",
         f"- Compute nodes (DGX systems / GB300 trays): **{c['dgx']}**, GPUs: **{c['gpus']}**",
         f"- Racks: **{c['racks']}**, power feeds: **{c['feeds']}**, IPs: **{c['ips']}**",
         f"- Cables: **{c['cables']}**", "",
         "## Devices by role", "", "| Role | Qty |", "|---|---|"]
    L += [f"| {r} | {n} |" for r, n in sorted(c["roles"].items())]
    L += ["", "## Devices by type", "", "| Device type | Source | Qty |", "|---|---|---|"]
    L += [f"| {t} | {types[t]['_source']} | {n} |" for t, n in sorted(c["types"].items())]
    L += ["", "## Cables by fabric and type", "", "| Fabric | Cable type | Qty |", "|---|---|---|"]
    L += [f"| {f} | {t} | {n} |" for (f, t), n in sorted(c["cables_by_type"].items())]
    budgets = "; ".join(
        (f"{name}: " if name else "") + "compute rack {} kW, management rack {} kW".format(
            p["racks"].get("budget_kw_dgx_rack", p["racks"].get("budget_kw_compute_rack")),
            p["racks"]["budget_kw_mgmt_rack"])
        for name, p in pod_specs(spec).items())
    L += ["", "## Rack peak power", "", f"Budgets: {budgets}.", "",
          "| Rack | Peak kW |", "|---|---|"]
    L += [f"| {r} | {kw:.2f} |" for r, kw in sorted(c["rack_kw"].items())]
    tot = sum(c["rack_kw"].values())
    L += [f"| **total** | **{tot:.1f}** |", ""]
    return "\n".join(L)


def cable_rows(design: Design) -> list[dict]:
    rows = []
    for o in design.all("dcim.cables"):
        a, b = o.data["a_terminations"], o.data["b_terminations"]
        cf = o.data["custom_fields"]
        rows.append({
            "label": o.data["label"], "fabric": cf["dgx_fabric"], "su": cf["dgx_su"] or "",
            "rail": cf["dgx_rail"] or "", "type": o.data["type"],
            "a_device": a[0].parent, "a_port": "+".join(t.name for t in a),
            "b_device": b[0].parent, "b_port": "+".join(t.name for t in b),
        })
    return rows


DEFAULT_ADDRESS_NOTE = ("Address plan avoids common private ranges used by the operator's "
                        "management network.")


def spec_note(spec: dict) -> str:
    """The one-line note on how the address plan relates to the operator's own ranges."""
    return spec.get("ipam", {}).get("address_plan_note", DEFAULT_ADDRESS_NOTE)


def ip_plan_markdown(spec: dict, design: Design) -> str:
    containers = ", ".join(f"`{p['ipam']['container']}`" for p in pod_specs(spec).values())
    L = ["# IP plan", "", "Generated by `bin/dgxnb export`. VRFs isolate every fabric; the whole",
         f"design sits in {containers}.", "",
         # Operator-specific range checks are config (spec ipam.address_plan_note), never
         # hard-coded: the default stays neutral so published output names no private network.
         spec_note(spec), "",
         "| VRF | Prefix | VLAN | Status | Description |", "|---|---|---|---|---|"]
    for o in design.all("ipam.prefixes"):
        vrf = o.data["vrf"].key[0] if "vrf" in o.data else "global"
        vlan = o.data["vlan"].key[0] if "vlan" in o.data else ""
        L.append(f"| {vrf} | {o.data['prefix']} | {vlan} | {o.data['status']} | "
                 f"{o.data['description']} |")
    per = Counter(o.key[0] for o in design.all("ipam.ip_addresses"))
    L += ["", "| VRF | Addresses |", "|---|---|"] + [f"| {v} | {n} |" for v, n in sorted(per.items())]
    L += ["", "Host numbering starts at .10 in every subnet; IPoIB compute uses the same host",
          "index on every rail subnet, so a node's rail-r address differs only in the rail block.", ""]
    return "\n".join(L)


def write_all(docs: Path, spec: dict, types: dict, design: Design) -> list[Path]:
    import json

    from . import drawio, graph, scene
    docs.mkdir(exist_ok=True)
    out = []
    p = docs / "topology-graph.json"
    p.write_text(json.dumps(graph.graph_json(spec, design), separators=(",", ":")))
    out.append(p)
    air, port_map = graph.air_json(spec, design)
    p = docs / "air-topology.json"
    p.write_text(json.dumps(air, indent=2))
    out.append(p)
    p = docs / "air-port-map.csv"
    with p.open("w", newline="") as f:
        csv.writer(f).writerows([["node", "air_port", "design_port"], *port_map])
    out.append(p)
    p = docs / "cable-map.csv"
    rows = cable_rows(design)
    with p.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    out.append(p)
    p = docs / "bom-generated.md"
    p.write_text(bom_markdown(spec, types, design))
    out.append(p)
    p = docs / "ip-plan.md"
    p.write_text(ip_plan_markdown(spec, design))
    out.append(p)
    p = docs / "superpod.drawio"
    p.write_text(drawio.drawio_xml(spec, types, design))
    out.append(p)
    if spec.get("hall"):                  # 3D scene needs the hall layout
        p = docs / "scene.json"
        p.write_text(json.dumps(scene.scene_json(spec, types, design), indent=1) + "\n")
        out.append(p)
    return out
